// Run: node scripts/build-assets.mjs
// 1) Figma PNGs -> AVIF/WebP (3G-friendly). 2) Figma SVG icons -> one inline sprite (0 extra requests).
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import sharp from "sharp";

mkdirSync("assets/img", { recursive: true });

// --- images -------------------------------------------------------------
const jobs = [
  ["connector", 1552], // sprite shown at 776 css px -> 2x
];
for (const [name, w] of jobs) {
  const src = sharp(`assets/raw/${name}.png`).resize({ width: w });
  await src.clone().avif({ quality: 55, effort: 6 }).toFile(`assets/img/${name}-${w}.avif`);
  await src.clone().webp({ quality: 78, effort: 6 }).toFile(`assets/img/${name}-${w}.webp`);
}

// --- icon sprite --------------------------------------------------------
const dir = "assets/icons";
const pathsOf = (svg) => [...svg.matchAll(/<path\b[^>]*\/>/g)].map((m) => m[0]);
const strip = (p) => p.replace(/\sid="[^"]*"/g, "").replaceAll('"#F9FAF4"', '"currentColor"'); // logo word takes the text colour; the lime triangle keeps its fill
let symbols = "";
const INK = new Set(["chevron-down", "arrow-up-right-light", "arrow-up-right-docs"]);

for (const f of readdirSync(dir).filter((f) => f.endsWith(".svg") && !f.startsWith("logo-") && !f.startsWith("v2-"))) {
  const name = f.replace(".svg", "");
  const svg = readFileSync(`${dir}/${f}`, "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  let inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  if (INK.has(name)) inner = inner.replaceAll('"#F9FAF4"', '"currentColor"'); // follows the nav / button text colour
  const keep = new Set([...inner.matchAll(/url\(#([^)]+)\)/g)].map((m) => m[1]));
  inner = inner
    .replace(/\sid="([^"]*)"/g, (_, id) => (keep.has(id) ? ` id="${name}-${id}"` : ""))
    .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${name}-${id})`);
  symbols += `<symbol id="${name}" viewBox="${viewBox}" fill="none">${inner.trim()}</symbol>`;
}

// Logo = Figma "yubit" + "pay" vectors on the 100x47 box the design uses (see hero cube).
const yubit = pathsOf(readFileSync(`${dir}/logo-yubit.svg`, "utf8"));
const pay = pathsOf(readFileSync(`${dir}/logo-pay.svg`, "utf8"));
const tri = yubit.pop(); // last path is the lime triangle
const triD = tri.match(/ d="([^"]+)"/)[1];
const word = `<g transform="translate(-0.01 -0.0376)">${yubit.map(strip).join("")}</g><g transform="translate(58.28 34.13)">${pay.map(strip).join("")}</g>`;
symbols += `<symbol id="logo-word" viewBox="0 0 100 47" fill="none">${word}</symbol>`;
symbols += `<symbol id="logo" viewBox="0 0 100 47" fill="none">${word}${strip(tri)}</symbol>`;

writeFileSync(
  "components/sprite.generated.ts",
  `// generated by scripts/build-assets.mjs - do not edit\nexport const SPRITE = ${JSON.stringify(symbols)};\nexport const TRI_D = ${JSON.stringify(triD)};\n`,
);
console.log("sprite bytes:", symbols.length);
